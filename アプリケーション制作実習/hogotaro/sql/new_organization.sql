-- 新しい団体と、その団体の最初の管理ユーザーを登録する手順とテンプレート。
-- 団体は運営が SQL で登録する（登録画面は作らない。要件定義 8 章）。
--
-- ■ 使い方
--   このファイルを丸ごと流さない。【 】を埋めて、STEP 1 から 1 つずつ実行し、結果を見てから次へ進む。
--   【 】を埋めないまま丸ごと流しても、STEP 2 の INSERT がエラー（Unknown column '【受け入れ上限】'）で止まり、何も登録されない。
--
-- ■ 決まりごと
--   ・ログイン ID は全団体で重複できない（staff.login_id は UNIQUE）。団体 1 の admin1 などとかぶらない ID にする
--     TODO: ログイン ID の付け方をチームで決めたら、ここに書く
--   ・初期パスワードは pass1234（全団体共通）。引き渡したら STEP 6 ですぐに変えてもらう
--   ・任意の項目で値が無いときは NULL と書く（' ' で囲まない）
USE hogotaro;

-- ============================================================
-- STEP 1  かぶりがないか確かめる
-- ============================================================
-- 0 件なら OK。1 件出たら、その団体はもう登録されている（やり直しなら STEP 3 から）
SELECT id, name FROM organizations WHERE name = '【団体名】';
-- 0 件なら OK。1 件出たら、そのログイン ID は使えないので別の ID にする
SELECT login_id FROM staff WHERE login_id = '【ログインID】';

-- ============================================================
-- STEP 2  団体を登録する
-- ============================================================
-- 必須: 団体名（50 文字まで）・住所（100 文字まで）・受け入れ上限（数字。' ' で囲まない）
-- 任意: 電話番号・メールアドレス・特記事項
-- 代表者名は特記事項に書く（代表者の列は作らない。決定 2-16）
INSERT INTO organizations (name, address, phone_number, email, capacity, notes) VALUES
  ('【団体名】', '【住所】', '【電話番号】', '【メールアドレス】', 【受け入れ上限】, '【特記事項】');

-- ============================================================
-- STEP 3  団体 ID を確かめる
-- ============================================================
-- ここで出た id を STEP 4 の【団体ID】に書く
-- 2 行出たら STEP 2 を 2 回流している。id の大きい方を消してから進む:
--   DELETE FROM organizations WHERE id = 【消す団体ID】;
SELECT id, name, capacity FROM organizations WHERE name = '【団体名】';

-- ============================================================
-- STEP 4  最初の管理ユーザーを登録する
-- ============================================================
-- 失敗しても STEP 2 からやり直さない（団体が 2 行になる）。エラーを直して STEP 4 だけ流し直す
-- password_hash は pass1234 を BCrypt にした値（data.sql と同じ）。書き換えない
-- user_type_id は数字を書かず、code = 'ADMIN' の行の id を引く
-- 必須: 団体ID（STEP 3 の id。' ' で囲まない）・ログインID（30 文字まで）・名前（30 文字まで）・性別・誕生日・電話番号
-- 任意: 登録日・住所・メールアドレス・特記事項
-- 性別は 'MALE' / 'FEMALE' / 'OTHER' のどれか。「男性」などの日本語は不可
--   （Gender enum の定数名で保存しているので、日本語だと staff を読み込めず、ログインが失敗する）
-- 日付は 'YYYY-MM-DD'（例: '1980-04-01'）
INSERT INTO staff (organization_id, login_id, password_hash, user_type_id, name, gender, birthday, joined_date, address, phone_number, email, notes) VALUES
  (【団体ID】, '【ログインID】', '$2b$10$9yRU3BKtyFtcmegXvhFcieVJqKk30fmk8fvqc...rDyT.lmJemrxi',
   (SELECT id FROM user_types WHERE code = 'ADMIN'),
   '【名前】', '【性別】', '【誕生日】', '【登録日】', '【住所】', '【電話番号】', '【メールアドレス】', '【特記事項】');

-- ============================================================
-- STEP 5  登録できたか確かめる
-- ============================================================
-- 1 行出て、user_type が ADMIN、団体名が STEP 2 のものなら OK
SELECT s.id, s.login_id, s.name, u.code AS user_type, o.id AS organization_id, o.name AS organization
  FROM staff s
  JOIN user_types u ON u.id = s.user_type_id
  JOIN organizations o ON o.id = s.organization_id
 WHERE s.login_id = '【ログインID】';

-- ============================================================
-- STEP 6  引き渡しとパスワードの変更（ここからは SQL ではなく画面で）
-- ============================================================
-- 1. 団体の担当者に、ログイン ID と初期パスワード pass1234 を伝える
-- 2. 担当者がログインしたら、すぐに スタッフ一覧 → 自分 → 編集 で、パスワード欄に新しいパスワードを入れて更新する
--    （pass1234 は全団体共通で、チーム全員が知っている。変えないままだと、ログイン ID を推測されたら入られる）
-- 3. ほかのスタッフのアカウントは、管理ユーザーがスタッフ登録画面から発行する（運営の作業はここまで）
